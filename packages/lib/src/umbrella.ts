// plx umbrella: one pnpm workspace over several repos, for development only.
//
// A package of one repo is developed in the app of another without a release
// in between (§ 5 PLX-Delivery): the directory above the clones becomes a pnpm
// workspace, so a dependency whose range the local version satisfies is linked
// to the clone instead of downloaded. `up` writes three things into that
// directory, the files marked as generated, and `down` deletes what is marked:
//
//   pnpm-workspace.yaml   the repos' own files merged: their package globs under
//                         the repo's name, catalogs, build allowances, registries
//                         and release-age settings, and linkWorkspacePackages
//   mise.local.toml       PLX_UMBRELLA_ROOT, which an app's bundler reads as its
//                         root, and NPM_CONFIG_WORKSPACE_DIR, by which a pnpm
//                         run inside a repo acts on the umbrella, not the repo
//   .plx-umbrella/        the watcher's process group and its log
//
// The repos' own lockfiles are not touched; the umbrella writes its own. The
// directory gets no `package.json`: a `packageManager` there would bind every
// repo's pnpm to one version, so pnpm runs from inside the repo that pins the
// newest one, with the variable naming the umbrella. By hand, `up` is: write
// those files, `mise trust mise.local.toml`, `pnpm install --force`, build the
// linked packages and run their `dev` scripts; `down` is: stop those, delete
// the files with `node_modules` and `pnpm-lock.yaml`, and
// `pnpm install --force` in each repo.
//
// Repos that pin different majors of pnpm are an error; a smaller difference
// is said in the result. Where two repos set the same key differently, a range that lies within the
// other wins (`^6.0.3` over `^6`), the longer release age wins, and anything
// else is an error naming both repos: nothing is picked silently.
import { join } from 'node:path';
import semver from 'semver';
import { parse, stringify } from 'yaml';
import type { Context } from './context.ts';
import { type Plan, run, write } from './effects.ts';
import { compareVersions, UsageError } from './version.ts';

export const UMBRELLA_MARK = 'Generated by `plx umbrella up`; `plx umbrella down` removes it.';
export const UMBRELLA_STATE = '.plx-umbrella';
export const UMBRELLA_ROOT_VAR = 'PLX_UMBRELLA_ROOT';
const WORKSPACE = 'pnpm-workspace.yaml';
const MISE = 'mise.local.toml';
const WORKSPACE_VAR = 'NPM_CONFIG_WORKSPACE_DIR';

export interface UmbrellaPackage {
  repo: string;
  /** Relative to the umbrella, as in `harness/packages/std`. */
  dir: string;
  name?: string;
  version?: string;
  scripts: string[];
  /** Every kind of dependency, name to the range as written. */
  dependencies: Record<string, string>;
}

export interface UmbrellaRepo {
  name: string;
  /** The text of its `pnpm-workspace.yaml`. */
  workspace: string;
  /** The `packageManager` of its root `package.json`. */
  packageManager?: string;
  packages: UmbrellaPackage[];
}

/** A dependency of one repo's package on a package another repo holds. */
export interface Link {
  from: string;
  fromRepo: string;
  to: string;
  toRepo: string;
  range: string;
  /** The version the other repo's clone is at. */
  version: string;
  /** Whether the range admits that version, which is when pnpm links it. */
  linked: boolean;
}

export interface Umbrella {
  dir: string;
  repos: string[];
  links: Link[];
  /** The linked packages whose `dev` script the watcher runs. */
  watched: string[];
  /** The linked packages without a `dev` script: built once, not rebuilt on a change. */
  unwatched: string[];
  /** What the reader should know besides: repos on different pnpm versions. */
  notices: string[];
  log: string;
  plan: Plan;
}

type Mapping = Record<string, unknown>;
const isMapping = (v: unknown): v is Mapping => v !== null && typeof v === 'object' && !Array.isArray(v);

/** The narrower of two ranges when one lies within the other, else undefined. */
function narrower(a: string, b: string): string | undefined {
  try {
    if (semver.subset(a, b)) return a;
    if (semver.subset(b, a)) return b;
  } catch {
    // not a range (a tag, a URL): only equal values agree
  }
  return undefined;
}

function mergeValue(key: string, a: unknown, b: unknown, from: string, into: string): unknown {
  if (a === undefined) return b;
  if (isMapping(a) && isMapping(b)) {
    const merged: Mapping = { ...a };
    for (const [k, v] of Object.entries(b)) merged[k] = mergeValue(`${key}.${k}`, a[k], v, from, into);
    return merged;
  }
  if (Array.isArray(a) && Array.isArray(b)) return [...new Set([...a, ...b])];
  if (a === b) return a;
  if (key === 'minimumReleaseAge' && typeof a === 'number' && typeof b === 'number') return Math.max(a, b);
  const within = typeof a === 'string' && typeof b === 'string' ? narrower(a, b) : undefined;
  if (within !== undefined) return within;
  throw new UsageError(
    `${into} and ${from} disagree on ${key} (${JSON.stringify(a)} and ${JSON.stringify(b)}); align them, or leave one out with --only`,
  );
}

/** The umbrella's workspace settings: every repo's own, merged key by key. */
export function mergeWorkspaces(repos: UmbrellaRepo[]): Mapping {
  const packages: string[] = [];
  let settings: Mapping = {};
  const seen: Record<string, string> = {};
  for (const repo of repos) {
    const own: unknown = parse(repo.workspace);
    const { packages: globs, ...rest } = isMapping(own) ? own : {};
    packages.push(repo.name);
    for (const glob of Array.isArray(globs) ? globs.map(String) : [])
      packages.push(glob.startsWith('!') ? `!${repo.name}/${glob.slice(1)}` : `${repo.name}/${glob}`);
    for (const [key, value] of Object.entries(rest)) {
      settings = { ...settings, [key]: mergeValue(key, settings[key], value, repo.name, seen[key] ?? repo.name) };
      seen[key] ??= repo.name;
    }
  }
  return { packages, ...settings, linkWorkspacePackages: true };
}

/** The range a manifest's `catalog:` entry stands for, or the range itself. */
function resolveRange(name: string, range: string, settings: Mapping): string {
  if (!range.startsWith('catalog:')) return range;
  const catalog = range.slice('catalog:'.length);
  const catalogs = isMapping(settings.catalogs) ? settings.catalogs : {};
  const entries = catalog === '' || catalog === 'default' ? settings.catalog : catalogs[catalog];
  const resolved = isMapping(entries) ? entries[name] : undefined;
  return typeof resolved === 'string' ? resolved : range;
}

/** Every dependency that crosses a repo boundary inside the umbrella, and whether pnpm links it. */
export function linksOf(repos: UmbrellaRepo[], settings: Mapping): Link[] {
  const byName = new Map<string, UmbrellaPackage>();
  for (const pkg of repos.flatMap((r) => r.packages)) if (pkg.name && pkg.version) byName.set(pkg.name, pkg);
  const links: Link[] = [];
  for (const pkg of repos.flatMap((r) => r.packages)) {
    for (const [name, written] of Object.entries(pkg.dependencies)) {
      const target = byName.get(name);
      if (!target?.version || target.repo === pkg.repo) continue;
      const range = resolveRange(name, written, settings);
      links.push({
        from: pkg.name ?? pkg.dir,
        fromRepo: pkg.repo,
        to: name,
        toRepo: target.repo,
        range,
        version: target.version,
        linked: semver.validRange(range) !== null && semver.satisfies(target.version, range),
      });
    }
  }
  return links.sort((a, b) => `${a.from} ${a.to}`.localeCompare(`${b.from} ${b.to}`));
}

/** The repo that pins the newest pnpm in its `packageManager`: the one the umbrella's pnpm runs from. */
export function newestPnpm(repos: UmbrellaRepo[]): string | undefined {
  const version = (r: UmbrellaRepo) => (r.packageManager?.startsWith('pnpm@') ? r.packageManager.slice(5) : '0');
  return [...repos].sort((a, b) => compareVersions(version(b), version(a)))[0]?.name;
}

/**
 * What to say where the repos pin different pnpm versions, or undefined where
 * they agree. Different majors are a UsageError: one install is not safely
 * shared across them.
 */
export function pnpmDifference(repos: UmbrellaRepo[]): string | undefined {
  const pins = repos.flatMap((r) =>
    r.packageManager?.startsWith('pnpm@')
      ? [{ repo: r.name, version: r.packageManager.slice(5).split('+')[0] ?? '' }]
      : [],
  );
  if (new Set(pins.map((p) => p.version)).size < 2) return undefined;
  const said = pins.map((p) => `${p.repo} ${p.version}`).join(', ');
  if (new Set(pins.map((p) => p.version.split('.')[0])).size > 1)
    throw new UsageError(`the repos pin different majors of pnpm (${said}); align them, or leave one out with --only`);
  return `the repos pin different pnpm versions (${said}); the umbrella installs from ${newestPnpm(repos)}`;
}

const filters = (names: string[]): string[] => names.flatMap((n) => ['--filter', n]);

/** Ends the watcher's process group, if one runs; the pid file's absence is "none". */
const stopWatcher = (dir: string) =>
  run('sh', ['-c', `kill -- -"$(cat ${UMBRELLA_STATE}/watch.pid 2>/dev/null)" 2>/dev/null || true`], { cwd: dir });

const quoted = (path: string) => `'${path.replaceAll("'", "'\\''")}'`;

/** What `up` does, from the repos as read. Pure; throws a UsageError where the repos disagree. */
export function planUp(dir: string, repos: UmbrellaRepo[]): Umbrella {
  const difference = pnpmDifference(repos);
  const settings = mergeWorkspaces(repos);
  const links = linksOf(repos, settings);
  const packages = new Map(repos.flatMap((r) => r.packages).map((p) => [p.name, p]));
  const linked = [...new Set(links.filter((l) => l.linked).map((l) => l.to))].sort();
  const has = (script: string) => (name: string) => packages.get(name)?.scripts.includes(script) === true;
  const watched = linked.filter(has('dev'));
  const pnpm = { cwd: join(dir, newestPnpm(repos) ?? ''), env: { [WORKSPACE_VAR]: dir } };
  const state = join(dir, UMBRELLA_STATE);
  const log = join(state, 'watch.log');
  // `set -m` gives the watcher a process group of its own, which `down` ends as a whole.
  const start = `set -m; nohup pnpm ${[...filters(watched), '--parallel', 'run', 'dev'].join(' ')} > ${quoted(log)} 2>&1 & echo $! > ${quoted(join(state, 'watch.pid'))}`;
  const plan: Plan = [
    stopWatcher(dir),
    run('mkdir', ['-p', join(dir, UMBRELLA_STATE)]),
    write(join(dir, WORKSPACE), `# ${UMBRELLA_MARK}\n${stringify(settings)}`),
    write(
      join(dir, MISE),
      `# ${UMBRELLA_MARK}\n[env]\n${UMBRELLA_ROOT_VAR} = "{{config_root}}"\n${WORKSPACE_VAR} = "{{config_root}}"\n`,
    ),
    run('mise', ['trust', '--quiet', MISE], { cwd: dir }),
    run('pnpm', ['install', '--force'], pnpm),
    ...(linked.some(has('build'))
      ? [run('pnpm', [...filters(linked.filter(has('build'))), 'run', 'build'], pnpm)]
      : []),
    ...(watched.length > 0 ? [run('sh', ['-c', start], pnpm)] : []),
  ];
  return {
    dir,
    repos: repos.map((r) => r.name),
    links,
    watched,
    unwatched: linked.filter((n) => !watched.includes(n)),
    notices: difference ? [difference] : [],
    log,
    plan,
  };
}

/** What `down` does for the repos the umbrella's own workspace file names. Pure. */
export function planDown(dir: string, repos: string[]): Plan {
  return [
    stopWatcher(dir),
    run('rm', ['-rf', UMBRELLA_STATE, 'node_modules', 'pnpm-lock.yaml', WORKSPACE, MISE], { cwd: dir }),
    // The variable names the repo itself, whatever a shell under the umbrella still carries.
    ...repos.map((repo) =>
      run('pnpm', ['install', '--force'], { cwd: join(dir, repo), env: { [WORKSPACE_VAR]: join(dir, repo) } }),
    ),
  ];
}

async function readOptional(ctx: Context, path: string): Promise<string | undefined> {
  try {
    return await ctx.readFile(path);
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code === 'ENOENT') return undefined;
    throw error;
  }
}

interface Manifest {
  name?: string;
  version?: string;
  packageManager?: string;
  scripts?: Record<string, string>;
  dependencies?: Record<string, string>;
  devDependencies?: Record<string, string>;
  peerDependencies?: Record<string, string>;
  optionalDependencies?: Record<string, string>;
}

async function readManifest(ctx: Context, path: string): Promise<Manifest | undefined> {
  const text = await readOptional(ctx, path);
  return text === undefined ? undefined : (JSON.parse(text) as Manifest);
}

/** The directories a `packages` glob names; one level of `*` is understood, as in changeset.ts. */
async function expand(ctx: Context, root: string, glob: string): Promise<string[]> {
  const star = glob.indexOf('*');
  if (star < 0) return [glob.replace(/\/$/, '')];
  const parent = glob.slice(0, star).replace(/\/$/, '');
  const entries = await ctx.readDir(join(root, parent)).catch(() => []);
  return entries.filter((e) => e.directory && !e.name.startsWith('.')).map((e) => join(parent, e.name));
}

async function readRepo(ctx: Context, dir: string, name: string, workspace: string): Promise<UmbrellaRepo> {
  const own: unknown = parse(workspace);
  const globs = isMapping(own) && Array.isArray(own.packages) ? own.packages.map(String) : [];
  const packages: UmbrellaPackage[] = [];
  for (const glob of globs.filter((g) => !g.startsWith('!'))) {
    for (const pkgDir of (await expand(ctx, join(dir, name), glob)).sort()) {
      const manifest = await readManifest(ctx, join(dir, name, pkgDir, 'package.json'));
      if (!manifest) continue;
      packages.push({
        repo: name,
        dir: join(name, pkgDir),
        name: manifest.name,
        version: manifest.version,
        scripts: Object.keys(manifest.scripts ?? {}),
        dependencies: {
          ...manifest.optionalDependencies,
          ...manifest.peerDependencies,
          ...manifest.devDependencies,
          ...manifest.dependencies,
        },
      });
    }
  }
  const root = await readManifest(ctx, join(dir, name, 'package.json'));
  return { name, workspace, packageManager: root?.packageManager, packages };
}

/** Whether the umbrella's files in `dir` are absent, `up`'s own, or someone else's (named). */
async function generated(ctx: Context, dir: string): Promise<{ up: boolean; foreign: string[] }> {
  const [workspace, mise] = await Promise.all([
    readOptional(ctx, join(dir, WORKSPACE)),
    readOptional(ctx, join(dir, MISE)),
  ]);
  const marked = (text: string | undefined) => text?.startsWith(`# ${UMBRELLA_MARK}`) === true;
  const foreign = [
    ...(workspace !== undefined && !marked(workspace) ? [WORKSPACE] : []),
    ...(mise !== undefined && !marked(mise) ? [MISE] : []),
  ];
  return { up: marked(workspace), foreign };
}

const refuse = (dir: string, foreign: string[]) =>
  new UsageError(`${dir} holds ${foreign.join(', ')} that plx umbrella did not generate; it is left alone`);

/**
 * Read the repos directly under `dir` (git roots that are pnpm workspaces,
 * narrowed by `only`) and plan `up`. Reads only; the caller applies the plan.
 */
export async function readUmbrella(ctx: Context, dir: string, only?: string[]): Promise<Umbrella> {
  const { foreign } = await generated(ctx, dir);
  if (foreign.length > 0) throw refuse(dir, foreign);
  const repos: UmbrellaRepo[] = [];
  for (const entry of (await ctx.readDir(dir)).sort((a, b) => a.name.localeCompare(b.name))) {
    if (!entry.directory || entry.name.startsWith('.') || entry.name === 'node_modules') continue;
    if (only && !only.includes(entry.name)) continue;
    const names = (await ctx.readDir(join(dir, entry.name)).catch(() => [])).map((e) => e.name);
    if (!names.includes('.git') || !names.includes(WORKSPACE)) continue;
    repos.push(await readRepo(ctx, dir, entry.name, await ctx.readFile(join(dir, entry.name, WORKSPACE))));
  }
  const missing = (only ?? []).filter((name) => !repos.some((r) => r.name === name));
  if (missing.length > 0) throw new UsageError(`no pnpm workspace in a git repo at ${missing.join(', ')} under ${dir}`);
  if (repos.length < 2) throw new UsageError(`an umbrella needs at least two repos with a ${WORKSPACE} under ${dir}`);
  return planUp(dir, repos);
}

/** Plan `down` from the umbrella's own workspace file; an empty plan when none is up. */
export async function readUmbrellaDown(ctx: Context, dir: string): Promise<{ repos: string[]; plan: Plan }> {
  const { up, foreign } = await generated(ctx, dir);
  if (foreign.length > 0) throw refuse(dir, foreign);
  if (!up) return { repos: [], plan: [] };
  const own: unknown = parse(await ctx.readFile(join(dir, WORKSPACE)));
  const globs = isMapping(own) && Array.isArray(own.packages) ? own.packages.map(String) : [];
  const repos = globs.filter((g) => !g.includes('/') && !g.startsWith('!'));
  return { repos, plan: planDown(dir, repos) };
}
